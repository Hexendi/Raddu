"""Loading and resolving the surah / reciter catalog.

The catalog is two static JSON files generated by ``tools/sync_catalog.py``
from the alquran.cloud and mp3quran.net public APIs.  Nothing is fetched at
runtime for metadata, so lookups and ``--help`` are instant and offline.
"""

from __future__ import annotations

import json
import pathlib
import random
import re
from dataclasses import dataclass, field
from typing import Iterable

DATA_DIR = pathlib.Path(__file__).resolve().parent / "data"


class CatalogError(Exception):
    """Raised when a user-supplied selector cannot be resolved."""


def _norm(token: str) -> str:
    """Fold a selector to its lookup form: lower-case, ascii, dash-separated."""
    t = token.strip().lower().replace("_", "-").replace(" ", "-")
    t = t.replace("'", "").replace("`", "").replace(".", "").replace("'", "")
    return re.sub(r"[^a-z0-9\u0600-\u06ff-]+", "-", t).strip("-")


@dataclass(frozen=True)
class Surah:
    number: int
    slug: str
    name_ar: str
    name_en: str
    meaning_en: str
    ayahs: int
    revelation: str
    aliases: tuple[str, ...]

    @property
    def filename(self) -> str:
        return f"{self.number:03d}-{self.slug}"


@dataclass(frozen=True)
class Style:
    code: str
    moshaf_id: int
    server: str
    label_ar: str
    label_en: str
    surah_count: int
    missing: tuple[int, ...]
    # Some sources do not use a uniform filename; when present this maps a
    # surah number to the exact basename to fetch.
    files: dict = field(default_factory=dict, compare=False, repr=False)

    def has(self, number: int) -> bool:
        return number not in self.missing


@dataclass(frozen=True)
class Reciter:
    code: str
    name_ar: str
    name_en: str
    default_style: str
    default_label_en: str
    codes: tuple[str, ...]
    styles: tuple[Style, ...]
    nationality: str | None = None
    source: str = "mp3quran.net"
    _by_style: dict = field(default_factory=dict, repr=False, compare=False)

    @property
    def style(self) -> Style:
        return next(s for s in self.styles if s.code == self.default_style)

    def style_by_code(self, code: str) -> Style | None:
        key = _norm(code)
        return next((s for s in self.styles if _norm(s.code) == key), None)


@dataclass(frozen=True)
class Track:
    """One resolved playable item."""

    surah: Surah
    reciter: Reciter
    style: Style

    @property
    def url(self) -> str:
        basename = self.style.files.get(self.surah.number)
        if not basename:
            basename = f"{self.surah.number:03d}.mp3"
        return f"{self.style.server}{basename}"

    @property
    def filename(self) -> str:
        return f"{self.surah.filename}-{self.reciter.code}-{self.style.code}.mp3"

    def describe(self) -> str:
        return (f"Surah {self.surah.name_en} ({self.surah.number}) - "
                f"{self.reciter.name_en} [{self.style.label_en}]")


# ISO country code -> spellings a user might type into `raddu -f`

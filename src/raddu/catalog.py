def _names_for(code: str | None) -> frozenset[str]:
    """Lookup spellings for a country code, pre-normalised."""
    if not code:
        return frozenset()
    return frozenset(_norm(n) for n in COUNTRIES.get(code, ()))


class Catalog:
    def __init__(self) -> None:
        self.surahs: list[Surah] = _load_surahs()
        self.reciters: list[Reciter] = _load_reciters()
        self._surah_index = _index(
            [(str(s.number), s.number) for s in self.surahs]
            + [(a, s.number) for s in self.surahs for a in s.aliases]
            + [(s.name_ar, s.number) for s in self.surahs]
            + [(s.name_en, s.number) for s in self.surahs]
        )
        self._reciter_index: dict[str, Reciter] = {}
        for r in self.reciters:
            for c in r.codes:
                self._reciter_index[_norm(c)] = r

    # -- surah resolution -------------------------------------------------
    def find_surah(self, token: str) -> Surah | None:
        key = _norm(token)
        if not key:
            return None
        num = self._surah_index.get(key)
        return self.surahs[num - 1] if num else None

    def random_surahs(self, count: int) -> list[Surah]:
        pool = list(self.surahs)
        random.shuffle(pool)
        return pool[: max(1, min(count, len(pool)))]

    # -- reciter resolution ----------------------------------------------
    def find_reciter(self, token: str) -> Reciter | None:
        """Resolve a reciter code.  Accepts ``code`` or ``code:style``."""
        base, _, style_code = token.partition(":")
        rec = self._reciter_index.get(_norm(base))
        if rec and style_code:
            # validate the style eagerly so the caller gets a clear error
            if rec.style_by_code(style_code) is None:
                raise CatalogError(
                    f"unknown style {style_code!r} for {rec.name_en}; "
                    f"available: {', '.join(s.code for s in rec.styles)}"
                )
        return rec

    def style_for(self, reciter: Reciter, style_code: str | None) -> Style:
        if not style_code:
            return reciter.style
        st = reciter.style_by_code(style_code)
        if st is None:
            raise CatalogError(
                f"unknown style {style_code!r} for {reciter.name_en}; "
                f"available: {', '.join(s.code for s in reciter.styles)}"
            )
        return st

    # -- combination ------------------------------------------------------
    def track(self, surah: Surah, reciter: Reciter, style_code: str | None = None) -> Track:
        style = self.style_for(reciter, style_code)
        if not style.has(surah.number):
            missing = ", ".join(str(n) for n in style.missing[:6])
            more = " ..." if len(style.missing) > 6 else ""
            alts = [s.code for s in reciter.styles if s.code != style.code]
            hint = (f"Try a different style: {', '.join(alts)}" if alts else
                    f"{reciter.name_en} has no other recording - see "
                    f"'raddu -R' for a reciter that covers all 114.")
            raise CatalogError(
                f"{reciter.name_en} does not have Surah {surah.name_en} "
                f"in the {style.label_en} recording "
                f"(available {style.surah_count}/114; missing {missing}{more}). "
                f"{hint}"
            )
        return Track(surah, reciter, style)

    def search(self, text: str) -> tuple[list[Surah], list[Reciter]]:
        q = _norm(text)
        surahs = [s for s in self.surahs
                  if q in _norm(s.slug) or q in _norm(s.name_en)
                  or q in _norm(s.meaning_en) or q in _norm(s.name_ar)]
        reciters = [r for r in self.reciters
                    if q in _norm(r.name_en) or q in _norm(r.name_ar)
                    or q in _norm(r.nationality or "")
                    or q in _names_for(r.nationality)
                    or any(q in _norm(c) for c in r.codes)]
        return surahs, reciters


def _index(pairs: Iterable[tuple]) -> dict:
    """Build a lookup table; the first occurrence of a key wins."""
    out = {}
    for key, val in pairs:
        out.setdefault(_norm(str(key)), val)
    return out


def _load_surahs() -> list[Surah]:
    raw = json.loads((DATA_DIR / "surahs.json").read_text(encoding="utf-8"))
    return [Surah(
        number=s["number"], slug=s["slug"], name_ar=s["name_ar"],
        name_en=s["name_en"], meaning_en=s["meaning_en"], ayahs=s["ayahs"],
        revelation=s["revelation"], aliases=tuple(s["aliases"]),
    ) for s in sorted(raw, key=lambda x: x["number"])]


def _load_reciters() -> list[Reciter]:
    raw = json.loads((DATA_DIR / "reciters.json").read_text(encoding="utf-8"))
    out = []
    for r in raw:
        styles = tuple(Style(
            code=s["code"], moshaf_id=s["moshaf_id"], server=s["server"],
            label_ar=s["label_ar"], label_en=s["label_en"],
            surah_count=s["surah_count"], missing=tuple(s["missing"]),
            files={int(k): v for k, v in (s.get("files") or {}).items()},
        ) for s in r["styles"])
        out.append(Reciter(
            code=r["code"], name_ar=r["name_ar"], name_en=r["name_en"],
            default_style=r["default_style"], default_label_en=r["default_label_en"],
            codes=tuple(r["codes"]), styles=styles,
            nationality=r.get("nationality"),
            source=r.get("source", "mp3quran.net"),
        ))
    return out


_CATALOG: Catalog | None = None


def catalog() -> Catalog:
    """Shared catalog instance (cheap to build, cached anyway)."""
    global _CATALOG
    if _CATALOG is None:
        _CATALOG = Catalog()
    return _CATALOG